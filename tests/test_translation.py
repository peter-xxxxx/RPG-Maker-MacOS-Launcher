class DetectionTests(unittest.TestCase):
    def test_detects_mv_www_layout(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            game = make_game(Path(temp) / "MV Game", "MV", www=True)
            layout = translation.detect_game_layout(game)
            self.assertIsNotNone(layout)
            assert layout is not None
            self.assertEqual(layout.engine, "MV")
            self.assertEqual(layout.game_path, game.absolute())
            self.assertEqual(layout.js_dir, game / "www/js")
            self.assertEqual(layout.data_dir, game / "www/data")
            self.assertEqual(layout.plugin_dir, game / "www/js/plugins")
            self.assertEqual(layout.index_dir, game / "www")

    def test_detects_mz_root_layout(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            game = make_game(Path(temp) / "MZ ゲーム", "MZ", www=False)
            layout = translation.detect_game_layout(game)
            self.assertIsNotNone(layout)
            assert layout is not None
            self.assertEqual(layout.engine, "MZ")
            self.assertEqual(layout.js_dir, game / "js")
            self.assertEqual(layout.data_dir, game / "data")

    def test_package_main_prefers_www_when_both_exist(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            game = make_game(Path(temp) / "ambiguous", "MV", www=True)
            # Add a second valid root layout.
            (game / "js").mkdir()
            (game / "js" / "rmmz_core.js").write_text("// core\n", encoding="utf-8")
            (game / "data").mkdir()
            layout = translation.detect_game_layout(game)
            assert layout is not None
            # package.json main points to www/index.html.
            self.assertEqual(layout.js_dir, game / "www/js")

    def test_unsupported_returns_none(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            game = Path(temp) / "plain"
            game.mkdir()
            self.assertIsNone(translation.detect_game_layout(game))


