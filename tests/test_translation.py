def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def make_game(base: Path, engine: str = "MV", www: bool = True) -> Path:
    app_root = base / "www" if www else base
    js_dir = app_root / "js"
    data_dir = app_root / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    (js_dir / "plugins").mkdir(parents=True, exist_ok=True)
    core_name = "rmmz_core.js" if engine == "MZ" else "rpg_core.js"
    (js_dir / core_name).write_text("// core\n", encoding="utf-8")
    (app_root / "index.html").write_text("<!doctype html>\n", encoding="utf-8")
    write_json(
        base / "package.json",
        {"main": "www/index.html" if www else "index.html"},
    )
    (js_dir / "plugins.js").write_text(
        """// Generated by RPG Maker.
var $plugins =
[
{"name":"FirstPlugin","status":true,"description":"First // still a string","parameters":{}},
{"name":"SecondPlugin","status":false,"description":"Second","parameters":{"mode":"fast"}}
];
""",
        encoding="utf-8",
    )
    return base


